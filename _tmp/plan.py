LINE = 4.57

def plan(pid, force_breaks=None, photo_scale=None):
    pg = PAGES[pid]
    cap, K, items = pg["cap"], pg["K"], pg["items"]
    total = sum(h for _, h, _ in items)
    print(f"\n=== {pid}  cap/栏={cap:.1f}mm({cap/LINE:.1f}行) x{K}  Σ={total:.1f}mm ({total/LINE:.1f}行)  均衡={total/K:.1f}mm  页底余={(K*cap-total)/LINE:.1f}行")
    # 目标：各栏均分；在元素边界取断点（洞/gap不与后段分离可接受）
    target = total / K
    cum = 0.0; breaks = []; col = 1
    colstart = 0
    holes = []
    for i, (t, h, key) in enumerate(items):
        if force_breaks and (i, ) and (col < K) and (i in force_breaks.get(pid, [])):
            breaks.append((col, i)); col += 1; colstart = i
        if t == "hole":
            holes.append((col, i, cum - (sum(h2 for _, h2, _ in items[colstart:i]) if False else 0), key))
        cum += h
    # 重算：逐元素累计 + 洞top（栏内偏移）
    cum = 0.0; col = 1; colstart = 0; colcum = 0.0
    breaks = []
    hole_tops = []
    fb = set(force_breaks.get(pid, [])) if force_breaks else set()
    for i, (t, h, key) in enumerate(items):
        if i in fb and col < K:
            breaks.append(i); col += 1; colstart = i; colcum = 0.0
        if t == "hole":
            hole_tops.append((col, i, colcum, key, h))
        colcum += h
        if i + 1 < len(items):
            pass
    # 无 force_breaks 时自动均衡断点
    if not fb:
        cum = 0.0; col = 1
        for i, (t, h, key) in enumerate(items):
            cum += h
            if col < K and cum >= target * col:
                # 洞/gap 边界微调：若下一元素是 hole，把断点放 hole 前
                breaks.append(i + 1); col += 1
        # 重算洞位
        col = 1; colcum = 0.0; colstart = 0; hole_tops = []
        for i, (t, h, key) in enumerate(items):
            if (i) in breaks and col < K:
                col += 1; colstart = i; colcum = 0.0
            if t == "hole":
                hole_tops.append((col, i, colcum, key, h))
            colcum += h
    # 各栏高度
    colh = [0.0] * K
    col = 1
    idx = 0
    for i, (t, h, key) in enumerate(items):
        if i in (breaks if breaks else []) and col < K:
            col += 1
        colh[col-1] += h
    for c in range(K):
        print(f"  栏{c+1}: {colh[c]:6.1f}mm ({colh[c]/LINE:5.1f}行)  底余 {(cap-colh[c])/LINE:5.1f}行")
    for (c, i, top, key, h) in hole_tops:
        flag = "  <<< 栏顶" if top < 1 else ""
        print(f"  洞[{key}] 栏{c} top={top:6.2f}mm (元素#{i}){flag}")
    return breaks, hole_tops

