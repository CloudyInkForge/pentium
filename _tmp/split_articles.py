def count_words(text):
    cjk = sum(1 for ch in text if not ch.isspace() and ord(ch) > 127)
    west = len(re.findall(r"[A-Za-z0-9]+(?:[.,/'’-][A-Za-z0-9]+)*", text))
    return cjk + west

